const range = (from: string, to: string): TimeRange => ({ from, to })

function week(weekday: TimeRange[], overrides: Partial<WeeklyHours> = {}): WeeklyHours {
  return { sun: weekday, mon: weekday, tue: weekday, wed: weekday, thu: weekday, fri: weekday, sat: weekday, ...overrides }
}

const stations = (bar: 'bar' | 'drinks'): Station[] => [
  { id: 'grill', name: stationNames.grill },
  { id: 'hot', name: stationNames.hot },
  { id: 'cold', name: stationNames.cold },
  { id: bar, name: stationNames[bar] },
]

const durations: ReservationRules['durations'] = [
  { maxParty: 2, lunchMin: 75, dinnerMin: 90 },
  { maxParty: 4, lunchMin: 90, dinnerMin: 105 },
  { maxParty: 99, lunchMin: 120, dinnerMin: 150 },
]

interface SettingsInput {
  country: CountryCode
  currency: LocalCurrency
  pricing?: PricingOverrides
  stations: Station[]
  timeLimitMin: number | null
  peak: BranchSettings['dining']['peak']
  minSpendPerAdult: number | null
  lateHoldMin: number
  reservations: Partial<ReservationRules>
  /** Amounts in minor units; the BYO-container discount matches the packaging fee. */
  takeaway: Partial<Omit<TakeawayRules, 'packagingFee' | 'payAtPickupMax' | 'byoDiscount'>> & { packagingFee: number | null; payAtPickupMax: number | null }
  qrConfirm: boolean
  waitersTakePayment: boolean
  kds: { amberMin: number; redMin: number }
  idleLockMin: number
}

function settings(input: SettingsInput): BranchSettings {
  const profile = countryProfile(input.country)
  const m = (amount: number | null) => (amount === null ? null : money(amount, input.currency))
  return {
    pricing: input.pricing ?? {},
    businessDayCutoff: '04:00',
    dining: { timeLimitMin: input.timeLimitMin, peak: input.peak, minSpendPerAdult: m(input.minSpendPerAdult), lateHoldMin: input.lateHoldMin },
    reservations: {
      enabled: true,
      stepMin: 15,
      durations,
      dinnerFrom: '17:00',
      bufferMin: 10,
      maxCoversPer15: 16,
      walkInHoldbackPct: 20,
      largePartyAt: 9,
      largeParty: 'enquiry',
      depositPerGuest: null,
      cancelWindowH: 24,
      bookingWindowDays: 60,
      ...input.reservations,
    },
    takeaway: {
      enabled: true,
      maxPer15: 5,
      prepMin: 20,
      ...input.takeaway,
      payAtPickupMax: m(input.takeaway.payAtPickupMax),
      packagingFee: m(input.takeaway.packagingFee),
      byoDiscount: m(input.takeaway.packagingFee),
    },
    qr: { mode: 'staffOpens', confirmByWaiter: input.qrConfirm, maxQtyPerItem: 10 },
    discounts: { cashierLimitBp: 1000 },
    permissions: { managersCanChangePrice: false, waitersTakePayment: input.waitersTakePayment },
    kds: { ...input.kds, sound: true },
    stations: input.stations,
    tenders: profile.tenders.map((t) => t.id),
    receipts: {
      footer: L(
        'Thank you for dining with us.',
        '謝謝光臨，期待再見。',
        '谢谢光临，期待再见。',
        'Terima kasih sudah bersantap bersama kami.',
        'Terima kasih kerana menjamu selera bersama kami.',
        'ご来店ありがとうございました。',
        '방문해 주셔서 감사합니다.',
      ),
      feedbackQr: true,
    },
    labour: { dailyLimitH: profile.labour.dailyLimitH },
    notifications: { dailyEmail: true, lowRatingAt: 2 },
    idleLockMin: input.idleLockMin,
  }
}

