// Writes api/_route-table.ts from the files in api/_routes, one route per file:
//   api/_routes/auth/login.ts                 → /auth/login
//   api/_routes/b/[branch]/devices/index.ts   → /b/:branch/devices
// Each entry is a dynamic import with a literal path, so Vercel bundles every route file but
// a cold start only loads the one it serves. `npm run dev` and `npm run build` run this; a
// unit test fails if the table is out of date.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const ROUTES_DIR = join(root, 'api', '_routes')
export const TABLE_FILE = join(root, 'api', '_route-table.ts')

export function routeFiles(dir = ROUTES_DIR): string[] {
  const files: string[] = []
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) files.push(...routeFiles(path))
    else if (name.endsWith('.ts') && !name.startsWith('_') && !name.endsWith('.test.ts')) files.push(relative(ROUTES_DIR, path).split(sep).join('/'))
  }
  return files
}

export function patternOf(file: string): string {
  const segments = file
    .replace(/\.ts$/, '')
    .split('/')
    .filter((segment, i, all) => !(segment === 'index' && i === all.length - 1))
    .map((segment) => (/^\[\w+\]$/.test(segment) ? `:${segment.slice(1, -1)}` : segment))
  return `/${segments.join('/')}`
}

export function renderTable(files: readonly string[]): string {
  const entries = [...files]
    .sort()
    .map((file) => `  { pattern: '${patternOf(file)}', load: () => import('./_routes/${file.replace(/\.ts$/, '.js')}') },`)
  return [
    '// Generated by scripts/gen-routes.ts from the files in api/_routes. Don’t edit by hand.',
    "import type { RouteDefinition } from '../lib/http/router.js'",
    '',
    'export const routeTable: RouteDefinition[] = [',
    ...entries,
    ']',
    '',
  ].join('\n')
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const files = routeFiles()
  const next = renderTable(files)
  let current = ''
  try {
    current = readFileSync(TABLE_FILE, 'utf8')
  } catch {
    // first run
  }
  if (current !== next) writeFileSync(TABLE_FILE, next)
  console.log(`api routes: ${files.length}${current === next ? '' : ' (table updated)'}`)
}
